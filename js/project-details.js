function renderProjectDetails() {
    const params = new URLSearchParams(window.location.search);
    const projectId = params.get('project') || 'the-grand-machal-resorts';
    const project = projectDetails[projectId] || projectDetails['the-grand-machal-resorts'];

    if (!project) return;

    // Document title
    document.title = `${project.name} | STARLINE ADVENTURES PVT LTD`;

    const nameEl = document.getElementById('projectName');
    const locationEl = document.getElementById('projectLocation');
    const typeEl = document.getElementById('projectType');
    const overviewEl = document.getElementById('projectOverview');
    const workIntroEl = document.getElementById('projectWorkIntro');
    const workListEl = document.getElementById('projectWorkList');
    const specsEl = document.getElementById('projectSpecs');
    const galleryEl = document.getElementById('projectGallery');

    if (nameEl) nameEl.textContent = project.name;
    if (locationEl) locationEl.textContent = project.location ? `📍 ${project.location}` : '';
    if (typeEl) typeEl.textContent = project.type || 'PROJECT';
    if (overviewEl) overviewEl.textContent = project.overview || '';
    if (workIntroEl) workIntroEl.textContent = project.workIntro || '';

    if (workListEl && Array.isArray(project.work)) {
        workListEl.innerHTML = project.work
            .map(item => `<div class="project-work-item"><span class="work-check">✔</span><span>${item}</span></div>`)
            .join('');
    }

    if (specsEl && Array.isArray(project.specifications)) {
        specsEl.innerHTML = project.specifications
            .map(([key, val]) => `
                <div class="project-spec-row">
                    <dt>${key}</dt>
                    <dd>${val}</dd>
                </div>
            `)
            .join('');
    }

    if (galleryEl && Array.isArray(project.gallery)) {
        galleryEl.innerHTML = project.gallery
            .map(([caption, src]) => `
                <figure class="project-gallery-item">
                    <img src="${src}" alt="${caption} - ${project.name}" loading="lazy" onerror="this.onerror=null; this.src='images/logo.jpeg';">
                    <figcaption>${caption}</figcaption>
                </figure>
            `)
            .join('');
    }
}

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', renderProjectDetails);
} else {
    renderProjectDetails();
}

